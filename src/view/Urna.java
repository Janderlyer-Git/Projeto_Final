    private void LiberarUrnaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_LiberarUrnaActionPerformed
        // TODO add your handling code here:
        if (telaAdm == null) {
        javax.swing.JOptionPane.showMessageDialog(this, "Abra a Urna pelo Painel Administrativo!");
        return;
    }

    if (telaAdm.getModeloCargos().getRowCount() == 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Nenhum cargo cadastrado para votação!");
        return;
    }

    // Extrai apenas os números do título digitado
    String tituloDigitado = TituloEleitor_Caixa.getText().replaceAll("[^0-9]", "");

    if (tituloDigitado.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Digite o Título de Eleitor!");
        return;
    }

    // Procura o eleitor na tabela da TelaAdm
    javax.swing.table.DefaultTableModel modeloEleitores = telaAdm.getModeloEleitores();
    linhaEleitorAtual = -1;

    for (int i = 0; i < modeloEleitores.getRowCount(); i++) {
        String tituloTabela = modeloEleitores.getValueAt(i, 3).toString().replaceAll("[^0-9]", "");
        if (tituloTabela.equals(tituloDigitado)) {
            linhaEleitorAtual = i;
            break;
        }
    }

    if (linhaEleitorAtual == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Título de Eleitor não cadastrado!");
        return;
    }

    // Verifica se o eleitor já votou
    String jaVotou = modeloEleitores.getValueAt(linhaEleitorAtual, 4).toString();
    if (jaVotou.equalsIgnoreCase("Sim")) {
        javax.swing.JOptionPane.showMessageDialog(this, "Este eleitor já registrou seu voto!");
        return;
    }

    // Libera o teclado e inicia pelo primeiro cargo
    indiceCargoAtual = 0;
    bloquearUrna(false);
    carregarCargoAtual();
        
    }//GEN-LAST:event_LiberarUrnaActionPerformed

