// Trava ou destrava os botões da urna
private void bloquearUrna(boolean bloquear) {
    urnaLiberada = !bloquear;
    javax.swing.JButton[] botoes = {Btn0, Btn1, Btn2, Btn3, Btn4, Btn5, Btn6, Btn7, Btn8, Btn9, Branco, Corrigir, Confirmar};

    for (javax.swing.JButton btn : botoes) {
        btn.setEnabled(!bloquear);
    }

    TituloEleitor_Caixa.setEnabled(bloquear);
    LiberarUrna.setEnabled(bloquear);

    if (bloquear) {
        CargoVoto.setText("AGUARDANDO ELEITOR");
        NomeVoto.setText("Nome:");
        PartidoVoto.setText("Partido:");
        FotoVoto.setIcon(null);
        FotoVoto.setText("Foto");
        atualizarQuadrados("", 0);
    }
}

// Mostra apenas os quadrados do cargo atual e preenche os dígitos
private void atualizarQuadrados(String numero, int digitosCargo) {
    javax.swing.JLabel[] quadrados = {Digito1, Digito2, Digito3, Digito4, Digito5};

    for (int i = 0; i < quadrados.length; i++) {
        quadrados[i].setVisible(i < digitosCargo);
        if (i < numero.length()) {
            quadrados[i].setText(String.valueOf(numero.charAt(i)));
        } else {
            quadrados[i].setText("");
        }
    }
}

// Prepara a tela branca para o cargo da vez
private void carregarCargoAtual() {
    numeroDigitado = "";
    votoBranco = false;

    javax.swing.table.DefaultTableModel modeloCargos = telaAdm.getModeloCargos();
    String nomeCargo = modeloCargos.getValueAt(indiceCargoAtual, 1).toString();
    int digitosCargo = Integer.parseInt(modeloCargos.getValueAt(indiceCargoAtual, 2).toString());

    CargoVoto.setText(nomeCargo.toUpperCase());
    NomeVoto.setText("Nome:");
    PartidoVoto.setText("Partido:");
    FotoVoto.setIcon(null);
    FotoVoto.setText("Foto");
    atualizarQuadrados("", digitosCargo);
}

