    private void ConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ConfirmarActionPerformed
       
       javax.swing.table.DefaultTableModel modeloCargos = telaAdm.getModeloCargos();
    int digitosCargo = Integer.parseInt(modeloCargos.getValueAt(indiceCargoAtual, 2).toString());

    // Impede confirmar antes de preencher todos os dígitos (exceto voto em branco)
    if (!votoBranco && numeroDigitado.length() < digitosCargo) {
        javax.swing.JOptionPane.showMessageDialog(this, "Complete o número do candidato ou aperte BRANCO!");
        return;
    }

    // Avança para o próximo cargo ou finaliza a votação do eleitor
    indiceCargoAtual++;

    if (indiceCargoAtual < modeloCargos.getRowCount()) {
        carregarCargoAtual();
    } else {
        // Marca na tabela da TelaAdm que este eleitor já votou
        telaAdm.getModeloEleitores().setValueAt("Sim", linhaEleitorAtual, 4);

        javax.swing.JOptionPane.showMessageDialog(this, "FIM! Voto registrado com sucesso.");
        TituloEleitor_Caixa.setText("");
        bloquearUrna(true);
    } 
        
    }//GEN-LAST:event_ConfirmarActionPerformed

